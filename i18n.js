const htmlLang = { en: "en", cn: "zh-CN", kr: "ko", jp: "ja" };
let lang = "en";

try {
  const saved = localStorage.getItem("aureon-lang");
  if (saved && ui[saved]) lang = saved;
} catch { /* private mode */ }

export function getLang() {
  return lang;
}

export function setLang(code) {
  if (!ui[code]) return;
  lang = code;
  try { localStorage.setItem("aureon-lang", code); } catch { /* ignore */ }
}

export function htmlLanguage() {
  return htmlLang[lang] || "en";
}

export function t(key) {
  return (ui[lang] && ui[lang][key]) || ui.en[key] || key;
}

export function tr(text) {
  if (!text || lang === "en") return text;
  const table = msg[lang];
  if (table && table[text]) return table[text];
  const index = lang === "cn" ? 1 : lang === "kr" ? 2 : 3;
  for (const rule of patterns) {
    const match = text.match(rule[0]);
    if (match) return rule[index].replaceAll("{id}", match[1]);
  }
  return text;
}
